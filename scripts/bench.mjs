#!/usr/bin/env node
import { writeFileSync } from 'node:fs';
/**
 * Reproducible benchmarks over generated documents. Writes docs/benchmarks.md
 * with the machine description and date so numbers can be compared between
 * releases. Run after `npm run build`.
 */
import { cpus, platform, release, totalmem } from 'node:os';
import { performance } from 'node:perf_hooks';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const { validateDtcg } = await import(`${root}packages/open-design-tokens/dist/validator.js`);
const { lintDtcg } = await import(`${root}packages/open-design-tokens/dist/linter.js`);

/** Builds a document with `n` tokens where each alias chain is `depth` long. */
function generate(n, depth) {
  const doc = { $type: 'color' };
  const groups = Math.max(1, Math.floor(n / 50));
  for (let g = 0; g < groups; g += 1) {
    const group = {};
    for (let t = 0; t < 50 && g * 50 + t < n; t += 1) {
      const idx = g * 50 + t;
      if (idx % (depth + 1) === 0 || depth === 0) {
        group[`t${t}`] = {
          $value: { colorSpace: 'srgb', components: [(idx % 255) / 255, 0.5, 0.25] },
        };
      } else {
        const prevT = t - 1;
        group[`t${t}`] =
          prevT >= 0
            ? { $value: `{g${g}.t${prevT}}` }
            : { $value: { colorSpace: 'srgb', components: [0, 0, 0] } };
      }
    }
    doc[`g${g}`] = group;
  }
  return doc;
}

function time(fn, runs = 5) {
  const samples = [];
  for (let i = 0; i < runs; i += 1) {
    const t0 = performance.now();
    fn();
    samples.push(performance.now() - t0);
  }
  samples.sort((a, b) => a - b);
  return samples[Math.floor(samples.length / 2)];
}

const rows = [];
for (const n of [100, 1_000, 10_000, 50_000]) {
  for (const depth of [1, 5]) {
    const doc = generate(n, depth);
    const json = JSON.stringify(doc);
    const v = time(() => validateDtcg(doc));
    const vs = time(() => validateDtcg(json));
    const l = time(() => lintDtcg(doc, { extends: ['recommended'] }));
    rows.push({ n, depth, v, vs, l });
    console.log(
      `${String(n).padStart(6)} tokens, depth ${depth}: validate ${v.toFixed(1)} ms (string ${vs.toFixed(1)} ms), lint ${l.toFixed(1)} ms`,
    );
  }
}

const cpu = cpus()[0]?.model ?? 'unknown CPU';
let md = `# Benchmarks\n\nGenerated by \`npm run bench\`. Median of 5 runs on ${cpu}, ${cpus().length} cores, ${(totalmem() / 2 ** 30).toFixed(0)} GB, ${platform()} ${release()}, Node ${process.version}, ${new Date().toISOString().slice(0, 10)}.\n\n`;
md += `Documents are generated: \`n\` color tokens in groups of 50, where every alias chain is \`depth\` hops long. Times are milliseconds.\n\n| Tokens | Alias depth | validate (object) | validate (JSON string) | lint (recommended) |\n|---:|---:|---:|---:|---:|\n`;
for (const r of rows)
  md += `| ${r.n.toLocaleString('en-US')} | ${r.depth} | ${r.v.toFixed(1)} | ${r.vs.toFixed(1)} | ${r.l.toFixed(1)} |\n`;
writeFileSync(`${root}docs/benchmarks.md`, md);
console.log('wrote docs/benchmarks.md');
